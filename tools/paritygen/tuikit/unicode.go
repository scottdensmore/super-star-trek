package main

import (
	"bufio"
	"fmt"
	"os"

	"github.com/clipperhouse/displaywidth"
	"github.com/mattn/go-runewidth"
	"github.com/rivo/uniseg"
)

// Per-codepoint property bits written to tables.rs:
//
//	bits 0-1: displaywidth property (0 default, 1 zero width, 2 wide, 3 East Asian ambiguous)
//	bits 2-4: rivo/uniseg single-rune width (0..4)
//	bit  5  : rivo/uniseg Extended_Pictographic (detected through VS15/VS16 behaviour)
//	bits 6-7: go-runewidth RuneWidth, EastAsianWidth=false
//	bits 8-9: go-runewidth RuneWidth, EastAsianWidth=true
func codepointProps(r rune) uint16 {
	var dw uint16
	if r < 0x80 {
		if r <= 0x1F || r == 0x7F {
			dw = 1
		}
	} else {
		s := string(r)
		w0 := displaywidth.Options{}.String(s)
		wEA := displaywidth.Options{EastAsianWidth: true}.String(s)
		switch {
		case w0 == 0:
			dw = 1
		case w0 == 2:
			dw = 2
		case w0 == 1 && wEA == 2:
			dw = 3
		case w0 == 1:
			dw = 0
		default:
			panic(fmt.Sprintf("unexpected displaywidth %d for %U", w0, r))
		}
	}

	uw := uniseg.StringWidth(string(r))
	if uw < 0 || uw > 4 {
		panic("uniseg width out of range")
	}
	var ext uint16
	if uniseg.StringWidth(string(r)+"️") == 2 && uniseg.StringWidth(string(r)+"︎") == 1 {
		ext = 1
	}

	c := runewidth.NewCondition()
	c.EastAsianWidth = false
	c.StrictEmojiNeutral = true
	rw := c.RuneWidth(r)
	cea := runewidth.NewCondition()
	cea.EastAsianWidth = true
	cea.StrictEmojiNeutral = true
	rwEA := cea.RuneWidth(r)

	return dw | uint16(uw)<<2 | ext<<5 | uint16(rw)<<6 | uint16(rwEA)<<8
}

func genTables(path string) {
	f, err := os.Create(path)
	if err != nil {
		panic(err)
	}
	w := bufio.NewWriter(f)
	fmt.Fprintln(w, "// @generated by tools/paritygen/tuikit (unicode.go). Do not edit.")
	fmt.Fprintln(w, "//")
	fmt.Fprintln(w, "// Run-length encoded per-codepoint width properties computed by the Go")
	fmt.Fprintln(w, "// libraries themselves (clipperhouse/displaywidth v0.11.0, rivo/uniseg v0.4.7,")
	fmt.Fprintln(w, "// mattn/go-runewidth v0.0.27). Each entry is (first codepoint, bits); the")
	fmt.Fprintln(w, "// entry applies until the next entry's codepoint. Bit layout: see")
	fmt.Fprintln(w, "// `super::Props`.")
	fmt.Fprintln(w, "")
	fmt.Fprintln(w, "#[rustfmt::skip]")
	fmt.Fprintln(w, "pub(crate) static RANGES: &[(u32, u16)] = &[")
	prev := uint16(0xFFFF)
	n := 0
	for r := rune(0); r <= 0x10FFFF; r++ {
		var p uint16
		if r >= 0xD800 && r <= 0xDFFF {
			p = prev // surrogates never occur in Rust strings
		} else {
			p = codepointProps(r)
		}
		if p != prev {
			fmt.Fprintf(w, "(0x%X,0x%X),", r, p)
			n++
			if n%8 == 0 {
				fmt.Fprintln(w)
			}
			prev = p
		}
	}
	fmt.Fprintln(w, "\n];")
	if err := w.Flush(); err != nil {
		panic(err)
	}
	f.Close()
	fmt.Fprintf(os.Stderr, "  %s: %d ranges\n", path, n)
}
